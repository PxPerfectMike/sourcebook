local Learned = ns.Learned

T("ParseGUID reads creatures and objects", function()
	eq({ Learned.ParseGUID("Creature-0-4372-0-17-6-00005A1B2C") }, { "creature", 6 })
	eq({ Learned.ParseGUID("GameObject-0-4372-0-17-1731-00005A1B2C") }, { "object", 1731 })
	eq({ Learned.ParseGUID("Vehicle-0-1-0-1-28782-0000000000") }, { "creature", 28782 })
	eq(Learned.ParseGUID("Player-4372-0ABCDEF0"), nil)
	eq(Learned.ParseGUID("Item-4372-0-4000000001"), nil)
	eq(Learned.ParseGUID(nil), nil)
	eq(Learned.ParseGUID(12), nil)
end)

T("Record counts loots and hits per source", function()
	local db = Learned.Init({})
	Learned.Record(db, "d", 6, "Kobold Vermin", { [2589] = true }, { m = 1429, x = 49, y = 36 })
	Learned.Record(db, "d", 6, nil, {}, nil)
	Learned.Record(db, "d", 6, nil, { [2589] = true, [159] = true }, nil)
	eq(db.src.d6.k, 3)
	eq(db.src.d6.n, "Kobold Vermin")
	eq(db.src.d6.m, 1429)
	eq(db.item[2589].d6, 2)
	eq(db.item[159].d6, 1)
end)

T("ForItem gives a rate only after enough loots", function()
	local db = Learned.Init({})
	for _ = 1, 4 do
		Learned.Record(db, "d", 6, "Kobold Vermin", { [2589] = true }, nil)
	end
	local e = Learned.ForItem(db, 2589)[1]
	eq(e.hits, 4)
	eq(e.loots, 4)
	eq(e.rate, nil)
	Learned.Record(db, "d", 6, nil, {}, nil)
	e = Learned.ForItem(db, 2589)[1]
	eq(e.loots, 5)
	ok(math.abs(e.rate - 0.8) < 1e-9)
	eq(e.kind, "d")
	eq(e.id, 6)
end)

T("ForItem sorts by hits and handles unknown items", function()
	local db = Learned.Init({})
	Learned.Record(db, "o", 1731, nil, { [2770] = true }, nil)
	Learned.Record(db, "d", 6, nil, { [2770] = true }, nil)
	Learned.Record(db, "d", 6, nil, { [2770] = true }, nil)
	local list = Learned.ForItem(db, 2770)
	eq(#list, 2)
	eq(list[1].kind .. list[1].id, "d6")
	eq(list[2].kind .. list[2].id, "o1731")
	eq(Learned.ForItem(db, 1), {})
	eq(Learned.ForItem(nil, 1), {})
end)

T("Record ignores a missing source", function()
	local db = Learned.Init({})
	Learned.Record(db, nil, 6, nil, { [1] = true })
	Learned.Record(db, "d", nil, nil, { [1] = true })
	eq(db.src, {})
end)
